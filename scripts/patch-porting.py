#!/usr/bin/env python3
"""Validate and render the source-layer inventory without fetching or applying patches."""

import argparse
import hashlib
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
import tomllib


ROOT = Path(__file__).resolve().parents[1]
LAYERS = {"packages/xo-server/": "backend", "packages/xo-web/": "frontend"}


def patch_paths(text):
    result = subprocess.run(
        ["git", "apply", "--numstat", "-z", "--"], input=text,
        text=True, capture_output=True, check=False, cwd=ROOT,
    )
    if result.returncode:
        raise ValueError("invalid patch diff")
    paths = set()
    records = iter(result.stdout.split("\0")[:-1])
    for record in records:
        added, removed, name = record.split("\t", 2)
        names = [name] if name else [next(records), next(records)]
        for value in names:
            path = PurePosixPath(value)
            if path.is_absolute() or ".." in path.parts:
                raise ValueError("invalid diff path")
            paths.add(value)
    if not paths:
        raise ValueError("patch has no changed source paths")
    return sorted(paths)


def collect(root):
    patch_dir = root / "patches"
    entries = tomllib.loads((patch_dir / "metadata.toml").read_text())["patches"]
    metadata = {entry["id"]: entry for entry in entries}
    if len(metadata) != len(entries):
        raise ValueError("duplicate metadata identity")
    series = (patch_dir / "series").read_text().splitlines()
    if not series or len(set(series)) != len(series):
        raise ValueError("empty or duplicate patch series")
    if any(not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*\.patch", name) for name in series):
        raise ValueError("invalid series filename")
    if set(series) != {path.name for path in patch_dir.glob("*.patch")}:
        raise ValueError("series does not cover patch files")
    if {Path(name).stem for name in series} != set(metadata):
        raise ValueError("metadata does not cover patch series")
    rows = []
    for name in series:
        entry = metadata[Path(name).stem]
        content = (patch_dir / name).read_bytes()
        paths = patch_paths(content.decode("utf-8"))
        layers = set()
        for path in paths:
            matches = [layer for prefix, layer in LAYERS.items() if path.startswith(prefix)]
            if not matches:
                raise ValueError(f"{name}: classify new source layer for {path}")
            layers.update(matches)
        declared = {key.removeprefix("porting_") for key in entry if key.startswith("porting_")}
        if declared != layers:
            raise ValueError(f"{name}: porting fields must match touched layers {sorted(layers)}")
        for layer in layers:
            value = entry[f"porting_{layer}"]
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"{name}: empty {layer} porting plan")
        rows.append({"name": name, "entry": entry, "paths": paths,
                     "layers": sorted(layers), "sha256": hashlib.sha256(content).hexdigest()})
    return rows


def render(rows):
    lines = [
        "# XO 5 patch layers and XO 6 porting inventory", "",
        "Generated by `python3 scripts/patch-porting.py --write`. Edit the porting fields",
        "in `patches/metadata.toml`, then regenerate. CI rejects missing layer plans or stale output.", "",
        "This inventory classifies the patched XO 5 source for [xcp-hl#53](https://github.com/Vagrantin/xcp-hl/issues/53).",
        "It does not establish that a",
        "feature is missing or a defect persists in current XO 6. Verify the exact target",
        "source and behavior before choosing what to port. No XO 6 build or appliance",
        "validation is claimed. UPSTREAM_XO remains unchanged.", "",
        "Backend rows identify behavior to retain or reassess. Frontend rows identify",
        "XO 5 UI code to rewrite or drop after target review. Mixed patches need both",
        "decisions; they are not wholly cosmetic or wholly portable. The layer is derived",
        "from Git's diff statistics, including removed files, not the metadata target hint.", "",
        "The manifest remains a planning input. It does not select, split, reorder or apply",
        "patches. `patches/series` still defines application order. The fork-versus-patch",
        "decision (#54/#43) and parallel-versus-cutover release policy remain separate.", "",
        "XO Lite is a separate product. Its deploy patcher and loader are outside this",
        "XO 5-to-XO 6 inventory. Appliance scripts, systemd units, RPM payloads and sudoers",
        "outside the XO diffs also need a separate deployment review when a capability moves.", "",
        f"## Complete series: {len(rows)} patches", "",
        "| Patch | Source layers | Purpose |", "| --- | --- | --- |",
    ]
    for row in rows:
        purpose = row["entry"]["description"].replace("|", "\\|")
        lines.append(f"| [{row['name']}](../patches/{row['name']}) | {', '.join(row['layers'])} | {purpose} |")
    for row in rows:
        entry = row["entry"]
        lines += ["", f"## {row['name']}", "",
                  f"Upstream: `{entry['upstream_commit']}`; declared versions: {', '.join(entry['applies_to'])}.",
                  f"Patch SHA-256: `{row['sha256']}`.", ""]
        for layer in row["layers"]:
            lines.append(f"- **{layer.capitalize()} plan:** {entry[f'porting_{layer}']}")
        lines += ["", "Touched source paths:", ""]
        lines += [f"- `{path}`" for path in row["paths"]]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate docs/patch-porting.md")
    args = parser.parse_args()
    try:
        rows = collect(ROOT)
        expected = render(rows)
        output = ROOT / "docs/patch-porting.md"
        if args.write:
            output.write_text(expected)
        elif not output.exists() or output.read_text() != expected:
            raise ValueError("stale docs/patch-porting.md; run with --write")
        print(f"PASS: {len(rows)} patches have complete layer plans and current documentation")
    except (KeyError, OSError, UnicodeError, ValueError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
